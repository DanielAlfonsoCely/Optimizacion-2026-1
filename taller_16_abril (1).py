from scipy.integrate import odeint
import numpy as np

# Parametros
beta = 0.00003
gamma = 0.1
N = 10000

# Definimos la EDO: le decimos a scipy cual es dI/dt
def modelo_SIS(I, t):
    dIdt = beta * (N - I) * I - gamma * I
    return dIdt

# Condicion inicial
I0 = 50

# Vector de tiempo: de 0 a 300 dias
t = np.linspace(0, 300, 300)

# scipy resuelve la EDO automaticamente
I = odeint(modelo_SIS, I0, t)

# Imprimimos resultados
print(f"{'Dia':<8} {'Infectados I(t)':>18} {'Susceptibles S(t)':>20}")
print("-" * 48)
for i in range(len(t)):
    print(f"{t[i]:<8.0f} {I[i][0]:>18.4f} {N - I[i][0]:>20.4f}")

print("-" * 48)
print(f"Equilibrio teorico:  I* = 6666.67,  S* = 3333.33")
print(f"Valor final: I* = {I[-1][0]:.4f}, S* = {N - I[-1][0]:.4f}")







