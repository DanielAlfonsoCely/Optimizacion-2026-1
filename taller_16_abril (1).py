from scipy.optimize import linprog
import math


# Z = 180X1 + 220X2

z = [-180 , -220]


A_ub = [
    [3,4],
    [2 ,1],
    [5,3]
]

b_ub = [120,80,150]

x1_lim = (0, None)
x2_lim = (0, None)

bounds = [x1_lim, x2_lim]

resultado = linprog(z, A_ub=A_ub, b_ub=b_ub, bounds=bounds, method='highs')

print(f"Estado {resultado.message}")
print(f"x1 = {resultado.x[0]}")
print(f"x2 = {resultado.x[1]}")
print(f"Ganancia máxima = {math.fabs(resultado.fun)}")







